static const var_t *find(const char *name)
{
    for (size_t i = 0; i < sizeof vars / sizeof vars[0]; i++)
        if (!strcmp(vars[i].name, name)) return &vars[i];
    return NULL;
}

static int show(const var_t *v, const char *path, int with_name)
{
    if (with_name) printf("%-35s ", v->name);
    if (v->kind == 'C') {
        size_t n = confstr(v->id, NULL, 0);
        if (n == 0) { puts(errno ? "undefined" : ""); return 0; }
        char *buf = malloc(n);
        if (!buf) return 1;
        confstr(v->id, buf, n);
        puts(buf);
        free(buf);
        return 0;
    }
    errno = 0;
    long r = v->kind == 'S' ? sysconf(v->id) : pathconf(path, v->id);
    if (r == -1 && errno) {
        if (with_name) { puts("undefined"); return 0; }
        fprintf(stderr, "getconf: %s: %s\n", v->name, strerror(errno));
        return 1;
    }
    if (r == -1) puts("undefined");
    else printf("%ld\n", r);
    return 0;
}

int main(int argc, char **argv)
{
    if (cervus_check_help_version(argc, argv, USAGE, "getconf")) return 0;
    int i = 1;
    if (i < argc && !strcmp(argv[i], "-v")) {
        if (i + 1 >= argc) { fputs(USAGE, stderr); return 2; }
        i += 2;
    } else if (i < argc && !strncmp(argv[i], "-v", 2)) {
        i++;
    }
    if (i < argc && !strcmp(argv[i], "--")) i++;
    if (i < argc && !strcmp(argv[i], "-a")) {
        const char *path = i + 1 < argc ? argv[i + 1] : "/";
        int last_id = -1;
        char last_kind = 0;
        for (size_t k = 0; k < sizeof vars / sizeof vars[0]; k++) {
            if (vars[k].id == last_id && vars[k].kind == last_kind) continue;
            last_id = vars[k].id;
            last_kind = vars[k].kind;
            show(&vars[k], path, 1);
        }
        return 0;
    }
    if (i >= argc) { fputs(USAGE, stderr); return 2; }
    const var_t *v = find(argv[i]);
    if (!v) { fprintf(stderr, "getconf: Unrecognized variable '%s'\n", argv[i]); return 2; }
    if (v->kind == 'P') {
        if (i + 1 >= argc) { fprintf(stderr, "getconf: %s needs a pathname\n", argv[i]); return 2; }
        return show(v, argv[i + 1], 0);
    }
    if (i + 1 < argc) { fputs(USAGE, stderr); return 2; }
    return show(v, NULL, 0);
}
