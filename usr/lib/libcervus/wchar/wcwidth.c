static int in_table(unsigned int c, const range_t *t, int n)
{
    int lo = 0, hi = n - 1;
    if (c < t[0].lo || c > t[n - 1].hi) return 0;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (c > t[mid].hi) lo = mid + 1;
        else if (c < t[mid].lo) hi = mid - 1;
        else return 1;
    }
    return 0;
}

int wcwidth(wchar_t wc)
{
    unsigned int c = (unsigned int)wc;
    if (c == 0) return 0;
    if (c < 0x20 || (c >= 0x7F && c < 0xA0)) return -1;
    if (c > 0x10FFFF || (c >= 0xD800 && c <= 0xDFFF)) return -1;
    if (in_table(c, ZERO, (int)(sizeof ZERO / sizeof ZERO[0]))) return 0;
    if (in_table(c, WIDE, (int)(sizeof WIDE / sizeof WIDE[0]))) return 2;
    return 1;
}

int wcswidth(const wchar_t *s, size_t n)
{
    int total = 0;
    for (size_t i = 0; i < n && s[i]; i++) {
        int w = wcwidth(s[i]);
        if (w < 0) return -1;
        total += w;
    }
    return total;
}
